/**
 * Filter events by Hijri month (1-12)
 */
export function getEventsForHijriMonth(month: number): IslamicEvent[] {
  return ISLAMIC_EVENTS.filter((e) => e.hijriMonth === month).sort((a, b) => a.hijriDay - b.hijriDay);
}

/**
 * Filter events by exact Hijri day and month
 */
export function getEventsForHijriDay(month: number, day: number): IslamicEvent[] {
  return ISLAMIC_EVENTS.filter((e) => e.hijriMonth === month && e.hijriDay === day);
}

/**
 * Get next upcoming events from the current Hijri date
 */
export function getUpcomingIslamicEvents(
  currentMonth: number,
  currentDay: number,
  limit: number = 6
): Array<IslamicEvent & { daysRemaining: number }> {
  // Approximate days remaining
  const eventsWithDistance = ISLAMIC_EVENTS.map((e) => {
    let diffDays: number;
    if (e.hijriMonth === currentMonth) {
      if (e.hijriDay >= currentDay) {
        diffDays = e.hijriDay - currentDay;
      } else {
        diffDays = (12 - currentMonth + e.hijriMonth) * 29.5 + (e.hijriDay - currentDay);
      }
    } else if (e.hijriMonth > currentMonth) {
      diffDays = (e.hijriMonth - currentMonth) * 29.5 + (e.hijriDay - currentDay);
    } else {
      diffDays = (12 - currentMonth + e.hijriMonth) * 29.5 + (e.hijriDay - currentDay);
    }

    return {
      ...e,
      daysRemaining: Math.max(0, Math.round(diffDays)),
    };
  });

  return eventsWithDistance.sort((a, b) => a.daysRemaining - b.daysRemaining).slice(0, limit);
}
